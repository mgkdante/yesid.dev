import { parse } from '@shuding/opentype.js';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_PATH = resolve(WEB_ROOT, 'vendor/fonts/lacquer/Lacquer-Regular.ttf');
const OUTPUT_ROOT = resolve(WEB_ROOT, 'static/svg/graffiti');
const SOURCE_COMMIT = '45b0855d499c093e4d1bd08926fec4e1a582e225';
const SOURCE_SHA256 = '140c21f71907a16952926ee354c81081092c90d599c89fe8b4557baeaebbbe83';
const WIDTH = 600;
const HEIGHT = 600;

const compositions = {
	en: {
		phrase: 'THE END',
		lines: [
			{ text: 'THE', baseline: 220, size: 230 },
			{ text: 'END', baseline: 500, size: 230 },
		],
	},
	fr: {
		phrase: 'LA FIN',
		lines: [
			{ text: 'LA', baseline: 220, size: 240 },
			{ text: 'FIN', baseline: 500, size: 230 },
		],
	},
	es: {
		phrase: 'FIN',
		lines: [{ text: 'FIN', baseline: 380, size: 300 }],
	},
};

function number(value) {
	return Number(value.toFixed(2)).toString();
}

function buildSvg(font, locale, composition) {
	const defs = [];
	const letters = [];
	let index = 0;

	for (const line of composition.lines) {
		const lineWidth = font.getAdvanceWidth(line.text, line.size, { kerning: true });
		const startX = (WIDTH - lineWidth) / 2;
		let characterIndex = 0;

		font.forEachGlyph(
			line.text,
			startX,
			line.baseline,
			line.size,
			{ kerning: true },
			(glyph, x, y, size) => {
				const character = line.text[characterIndex++];
				const id = `${locale}-${index}`;
				const bodyClip = `body-${id}`;
				const dripClip = `drip-${id}`;
				const path = glyph.getPath(x, y, size, {}, font).toPathData(2);
				const advance = ((glyph.advanceWidth ?? font.unitsPerEm) / font.unitsPerEm) * size;
				const originX = x + advance / 2;

				defs.push(
					`    <clipPath id="${bodyClip}" clipPathUnits="userSpaceOnUse"><rect x="-50" y="-50" width="700" height="${number(line.baseline + 50)}"/></clipPath>`,
					`    <clipPath id="${dripClip}" clipPathUnits="userSpaceOnUse"><rect x="-50" y="${number(line.baseline)}" width="700" height="${number(HEIGHT - line.baseline + 50)}"/></clipPath>`,
				);
				letters.push(
					`  <g data-letter="${character}" data-index="${index}">`,
					`    <path data-part="body" clip-path="url(#${bodyClip})" d="${path}"/>`,
					`    <path data-part="drip" data-origin-x="${number(originX)}" data-origin-y="${number(line.baseline)}" clip-path="url(#${dripClip})" d="${path}"/>`,
					'  </g>',
				);
				index += 1;
			},
		);
	}

	return `<!--
  Generated by scripts/build-graffiti.mjs from Google Fonts Lacquer.
  Source commit: ${SOURCE_COMMIT}
  Source TTF SHA-256: ${SOURCE_SHA256}
  Copyright 2019 The Lacquer Project Authors. SIL OFL 1.1.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" data-phrase="${composition.phrase}" fill="#000">
  <defs>
${defs.join('\n')}
  </defs>
${letters.join('\n')}
</svg>
`;
}

const check = process.argv.includes('--check');
const fontBuffer = await Bun.file(FONT_PATH).arrayBuffer();
const fontSha256 = createHash('sha256').update(Buffer.from(fontBuffer)).digest('hex');
if (fontSha256 !== SOURCE_SHA256) {
	throw new Error(
		`Lacquer source hash mismatch: expected ${SOURCE_SHA256}, received ${fontSha256}`,
	);
}
const font = parse(fontBuffer);
await mkdir(OUTPUT_ROOT, { recursive: true });

let drift = false;
for (const [locale, composition] of Object.entries(compositions)) {
	const outputPath = resolve(OUTPUT_ROOT, `the-end.${locale}.svg`);
	const expected = buildSvg(font, locale, composition);
	if (check) {
		let current = '';
		try {
			current = await readFile(outputPath, 'utf8');
		} catch {
			// A missing output is ordinary drift and is reported below.
		}
		if (current !== expected) {
			console.error(`[graffiti] drift: ${outputPath}`);
			drift = true;
		}
	} else {
		await writeFile(outputPath, expected);
		console.log(`[graffiti] wrote ${outputPath}`);
	}
}

if (drift) process.exit(1);
